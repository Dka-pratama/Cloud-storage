    private void btnChooseFileActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnChooseFileActionPerformed
        // TODO add your handling code here:
        JFileChooser chooser = new JFileChooser();
        int result = chooser.showOpenDialog(this);
        
        if(result == JFileChooser.APPROVE_OPTION) {
            selectedFile = chooser.getSelectedFile();
            lblFileName.setText(selectedFile.getName());
            txtFileName.setText(selectedFile.getName());
        }
    }//GEN-LAST:event_btnChooseFileActionPerformed

    private void btnUploadActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnUploadActionPerformed
        // TODO add your handling code here:
        if (selectedFile == null){
            JOptionPane.showMessageDialog(this, "Pilih dulu file nya");
            return;
        }
        
        DashboardForm.getInstance().setLoading(true);
        
        String customName = txtFileName.getText().trim();
        String tier = (String) cmbTier.getSelectedItem();
        
        btnUpload.setEnabled(false);
        btnUpload.setText("Uploading...");
        
        FileService fileService = new FileService();
        fileService.uploadFile(selectedFile, targetFolder, customName, tier, new FileService.UploadCallback() {
            @Override
            public void onSuccess() {
                JOptionPane.showMessageDialog(UploadDialog.this, "Upload Berhasil...");
                
                DashboardForm.getInstance().setLoading(false);
            }

            @Override
            public void onError(String message) {
                btnUpload.setEnabled(true);
                btnUpload.setText("Upload");
                JOptionPane.showMessageDialog(UploadDialog.this,"Gagal :" + message);
                
                DashboardForm.getInstance().setLoading(true);
            }
        });
    }//GEN-LAST:event_btnUploadActionPerformed

